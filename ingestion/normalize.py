from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

from ingestion.layout import (
    DIAnalysis,
    DIRegion,
    DISpan,
    FigureArtifact,
    LayoutArtifact,
    PageArtifact,
    ParagraphArtifact,
    Region,
    Span,
    TableArtifact,
    TableCell,
)


def normalize_layout(
    analysis_json: bytes, *, document: str, revision: str, pdf_sha256: str
) -> LayoutArtifact:
    """Normalize saved analysis only; never calls DI, renders images, or creates an index."""
    analysis = DIAnalysis.model_validate_json(analysis_json)
    page_numbers = {page.pageNumber for page in analysis.pages}
    if len(page_numbers) != len(analysis.pages):
        raise ValueError("analysis contains duplicate page numbers")
    issues = []
    unmodeled = sorted(set(json.loads(analysis_json)) - DIAnalysis.model_fields.keys())
    if unmodeled:
        issues.append(
            "Unmodeled analysis fields retained in raw artifact only: " + ", ".join(unmodeled)
        )
    for index, paragraph in enumerate(analysis.paragraphs):
        if not paragraph.content.strip():
            issues.append(f"/paragraphs/{index}: blank text preserved for reference stability")

    def regions(values: list[DIRegion]) -> tuple[Region, ...]:
        if any(value.pageNumber not in page_numbers for value in values):
            raise ValueError("bounding region references a missing page")
        return tuple(
            Region(page_number=value.pageNumber, polygon=tuple(value.polygon)) for value in values
        )

    def spans(values: list[DISpan]) -> tuple[Span, ...]:
        if any(value.offset + value.length > len(analysis.content) for value in values):
            raise ValueError("span extends past Unicode code-point content")
        return tuple(Span(offset=value.offset, length=value.length) for value in values)

    tables = []
    for index, table in enumerate(analysis.tables):
        table_id = f"{document}-table-{index + 1}"
        if not any(cell.kind == "columnHeader" for cell in table.cells):
            issues.append(
                f"{table_id}: missing explicit column headers; review continuation context"
            )
        if any(not cell.boundingRegions for cell in table.cells):
            issues.append(
                f"{table_id}: some cells lack page regions; table region is not cell precision"
            )
        tables.append(
            TableArtifact(
                table_id=table_id,
                row_count=table.rowCount,
                column_count=table.columnCount,
                cells=tuple(
                    TableCell(
                        row=cell.rowIndex,
                        column=cell.columnIndex,
                        row_span=cell.rowSpan,
                        column_span=cell.columnSpan,
                        kind=cell.kind,
                        text=cell.content,
                        regions=regions(cell.boundingRegions),
                        spans=spans(cell.spans),
                    )
                    for cell in table.cells
                ),
                regions=regions(table.boundingRegions),
                caption=table.caption.content if table.caption else None,
                footnotes=tuple(note.content for note in table.footnotes),
                element_refs=tuple(table.elements),
                spans=spans(table.spans),
            )
        )
    if analysis.tables:
        issues.append(
            "Table continuation/header and footnote associations require review before chunking; "
            "no same-column-count or adjacency heuristic has asserted a relationship."
        )
    figures = tuple(
        FigureArtifact(
            figure_id=f"{document}-figure-{index + 1}",
            provider_figure_id=figure.id,
            regions=regions(figure.boundingRegions),
            caption=figure.caption.content if figure.caption else None,
            footnotes=tuple(note.content for note in figure.footnotes),
            element_refs=tuple(figure.elements),
            spans=spans(figure.spans),
        )
        for index, figure in enumerate(analysis.figures)
    )
    if len({figure.id for figure in analysis.figures}) != len(analysis.figures):
        raise ValueError("analysis contains duplicate provider figure IDs")
    if figures:
        issues.append("Figure crops and vision descriptions are not generated by normalization.")
    return LayoutArtifact(
        document=document,
        revision=revision,
        pdf_sha256=pdf_sha256,
        analysis_sha256=hashlib.sha256(analysis_json).hexdigest(),
        api_version=analysis.apiVersion,
        content=analysis.content,
        pages=tuple(
            PageArtifact(
                page_number=page.pageNumber,
                width=page.width,
                height=page.height,
                unit=page.unit,
            )
            for page in analysis.pages
        ),
        tables=tuple(tables),
        figures=figures,
        paragraphs=tuple(
            ParagraphArtifact(
                paragraph_id=f"/paragraphs/{index}",
                text=paragraph.content,
                role=paragraph.role,
                regions=regions(paragraph.boundingRegions),
                spans=spans(paragraph.spans),
            )
            for index, paragraph in enumerate(analysis.paragraphs)
        ),
        issues=tuple(issues),
    )


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Normalize a saved DI analyzeResult without API calls."
    )
    parser.add_argument("--analysis", type=Path, required=True)
    parser.add_argument("--pdf", type=Path, required=True)
    parser.add_argument("--document", required=True)
    parser.add_argument("--revision", required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    artifact = normalize_layout(
        args.analysis.read_bytes(),
        document=args.document,
        revision=args.revision,
        pdf_sha256=hashlib.sha256(args.pdf.read_bytes()).hexdigest(),
    )
    with args.output.open("x") as output:
        output.write(artifact.model_dump_json(indent=2) + "\n")
    print(f"Saved layout with {len(artifact.issues)} review issues; not index-ready.")


if __name__ == "__main__":
    main()
